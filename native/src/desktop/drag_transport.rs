//! OLE boundary for native file drag-out; originals are copy-only, and Shift may move only the exclusive export copy generated for this operation.
use std::{
    path::PathBuf,
    sync::{
        atomic::{AtomicBool, Ordering},
        Arc,
    },
};
use windows::{
    core::{implement, Error, Result, BOOL, HRESULT},
    Win32::{
        Foundation::*,
        System::{Ole::*, SystemServices::*},
    },
};

#[path = "drag_transport_data.rs"]
mod data;
#[path = "drag_transport_preview.rs"]
mod preview;

struct Apartment;
impl Apartment {
    fn new() -> Result<Self> {
        unsafe {
            OleInitialize(None)?;
        }
        Ok(Self)
    }
}
impl Drop for Apartment {
    fn drop(&mut self) {
        unsafe {
            OleUninitialize();
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    Copied,
    Moved,
    Cancelled,
}

#[implement(IDropSource)]
struct Source {
    cancel: Arc<AtomicBool>,
}
impl IDropSource_Impl for Source_Impl {
    fn QueryContinueDrag(&self, escape: BOOL, keys: MODIFIERKEYS_FLAGS) -> HRESULT {
        continuation(escape.as_bool(), keys, self.cancel.load(Ordering::Acquire))
    }
    fn GiveFeedback(&self, _: DROPEFFECT) -> HRESULT {
        DRAGDROP_S_USEDEFAULTCURSORS
    }
}

fn continuation(escape: bool, keys: MODIFIERKEYS_FLAGS, cancelled: bool) -> HRESULT {
    if escape || cancelled || keys.contains(MK_RBUTTON) {
        DRAGDROP_S_CANCEL
    } else if !keys.contains(MK_LBUTTON) {
        DRAGDROP_S_DROP
    } else {
        S_OK
    }
}

/// Call on the STA UI thread owning the gesture; callers must ensure files are their own stable export snapshots.
/// OLE runs nested message loops: hold no UI RefCell borrow across this call, and window closure must set cancel.
/// Allow COPY only. Return values describe OLE outcomes, not proof that the target application persisted data.
/// This function does not own file lifetime; callers must not revoke files while targets may still read them.
pub fn drag_files(paths: &[PathBuf], cancel: Arc<AtomicBool>) -> Result<Outcome> {
    drag_files_with_preview(paths, cancel, None, DROPEFFECT_COPY)
}
/// Only for PNG copies exclusively generated by this application for this operation, never original user files.
pub(super) fn drag_export_snapshot(
    path: PathBuf,
    cancel: Arc<AtomicBool>,
    image: &super::drag_preview::Preview,
) -> Result<Outcome> {
    drag_files_with_preview(
        &[path],
        cancel,
        Some(image),
        DROPEFFECT_COPY | DROPEFFECT_MOVE,
    )
}
fn drag_files_with_preview(
    paths: &[PathBuf],
    cancel: Arc<AtomicBool>,
    image: Option<&super::drag_preview::Preview>,
    allowed: DROPEFFECT,
) -> Result<Outcome> {
    if cancel.load(Ordering::Acquire) {
        return Ok(Outcome::Cancelled);
    }
    let _apartment = Apartment::new()?;
    let payload = data::prepare(paths)?;
    if let Some(image) = image {
        // Previews are an enhancement; unavailable Shell helpers must not prevent CF_HDROP file copy.
        if let Err(error) = preview::attach(&payload.object, image) {
            eprintln!("native-drag-preview: {error}");
        }
    }
    let source: IDropSource = Source {
        cancel: cancel.clone(),
    }
    .into();
    if cancel.load(Ordering::Acquire) {
        return Ok(Outcome::Cancelled);
    }
    let mut effect = DROPEFFECT_NONE;
    let status = unsafe { DoDragDrop(&payload.object, &source, allowed, &mut effect) };
    completion(status, effect, &payload.object)
}
fn completion(
    status: HRESULT,
    effect: DROPEFFECT,
    object: &windows::Win32::System::Com::IDataObject,
) -> Result<Outcome> {
    let effect = if status == DRAGDROP_S_DROP {
        data::logical_effect(object)?.unwrap_or(effect)
    } else {
        effect
    };
    outcome(status, effect)
}

fn outcome(status: HRESULT, effect: DROPEFFECT) -> Result<Outcome> {
    if status == DRAGDROP_S_CANCEL {
        return Ok(Outcome::Cancelled);
    }
    status.ok()?;
    if status == DRAGDROP_S_DROP && effect == DROPEFFECT_COPY {
        Ok(Outcome::Copied)
    } else if status == DRAGDROP_S_DROP && effect == DROPEFFECT_MOVE {
        Ok(Outcome::Moved)
    } else if status == DRAGDROP_S_DROP && effect == DROPEFFECT_NONE {
        Ok(Outcome::Cancelled)
    } else {
        Err(Error::new(E_FAIL, "Unexpected native drag completion"))
    }
}

